#!/usr/bin/env python3
"""Compile exact Kodi Android ARMv7 translation units from CMake commands.

This is NOT a whole-Kodi build or a source-pattern test. It executes the
generated compiler invocations locally in disposable CI; no APK or upload.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys

TARGETS = (
    "xbmc/cores/VideoPlayer/VideoPlayerVideo.cpp",
    "xbmc/utils/BitstreamConverter.cpp",
)

# Direct compile_commands execution bypasses ExternalProject header builds.
# These names were verified against Kodi's Find*.cmake BUILD_DEP_TARGET calls.
# No general header->target guessing, no APK target, no shell commands.
GENERATED_HEADER_TARGETS = {
    "libavutil/pixfmt.h": "build-ffmpeg",
    "libavcodec/avcodec.h": "build-ffmpeg",
    "libavutil/dovi_meta.h": "build-ffmpeg",
    "fmt/format.h": "build-fmt",
    "spdlog/spdlog.h": "build-spdlog",
    "pcre2.h": "build-pcre2",
    "nlohmann/json.hpp": "build-nlohmann_json",
    "tinyxml2.h": "build-tinyxml2",
}
MAX_DEPENDENCY_RECOVERIES = 6


def recoverable_prerequisite(compiler_output: str, already_attempted: set[str]) -> str | None:
    """Return an explicitly audited target for one missing generated header."""
    import re

    missing = []
    for line in compiler_output.splitlines():
        match = re.search("fatal error: '([^']+)' file not found", line)
        if match:
            missing.append(match.group(1))
    if len(missing) != 1:
        return None
    target = GENERATED_HEADER_TARGETS.get(missing[0])
    return target if target not in already_attempted else None


def compile_units(database: Path, source_root: Path) -> None:
    commands = json.loads(database.read_text(encoding="utf-8"))
    if not isinstance(commands, list) or not commands:
        raise RuntimeError("CMAKE_COMPILE_COMMANDS_EMPTY")

    root = source_root.resolve()
    for suffix in TARGETS:
        matched = [
            command for command in commands
            if Path(str(command.get("file", ""))).as_posix().endswith(suffix)
        ]
        if len(matched) != 1:
            raise RuntimeError(f"COMPILATION_UNIT_NOT_UNIQUE {suffix} matches={len(matched)}")
        item = matched[0]
        cwd = Path(item["directory"]).resolve()
        source = Path(item["file"])
        source = (cwd / source).resolve() if not source.is_absolute() else source.resolve()
        if not source.is_file() or not source.is_relative_to(root):
            raise RuntimeError(f"REFUSE_OUTSIDE_CHECKOUT {source}")
        argv = item.get("arguments") or shlex.split(item["command"])
        if not argv:
            raise RuntimeError(f"NO_COMPILER_COMMAND {suffix}")
        # Generated by trusted Kodi CMake; only execute exact checked-out TU
        # and only if the compiler belongs to the configured Android NDK.
        ndk_root = os.environ.get("ANDROID_NDK_HOME", "")
        compilers = [Path(arg).resolve() for arg in argv[:2] if "clang++" in arg]
        if not ndk_root or not compilers or not any(
            compiler.is_relative_to(Path(ndk_root).resolve()) for compiler in compilers
        ):
            raise RuntimeError(f"NOT_PINNED_ANDROID_CLANG {suffix} command={argv[:2]}")
        # Compile database metadata is not evidence that argv actually compiles
        # the advertised TU. A full checkout path must appear in the real
        # compiler command, with explicit compile-only mode and ARMv7 target.
        cpp_args = [Path(arg) for arg in argv if arg.endswith(".cpp")]
        compiled_paths = [
            (cwd / arg).resolve() if not arg.is_absolute() else arg.resolve()
            for arg in cpp_args
        ]
        if compiled_paths != [source] or "-c" not in argv:
            raise RuntimeError(f"WRONG_COMPILED_SOURCE {suffix} matched={compiled_paths}")
        if not any("armv7" in arg.lower() for arg in argv):
            raise RuntimeError(f"NOT_ANDROID_ARMV7_COMMAND {suffix}")
        if "-o" not in argv or argv.index("-o") + 1 >= len(argv):
            raise RuntimeError(f"MISSING_OBJECT_OUTPUT {suffix}")
        obj = Path(argv[argv.index("-o") + 1])
        if obj.suffix != ".o":
            raise RuntimeError(f"NOT_OBJECT_OUTPUT {suffix}")
        print(f"GAZELLE_ANDROID_ARMV7_TU_START path={suffix}", flush=True)
        # Use only the explicit, source-reviewed Kodi ExternalProject target
        # names, and only on a single exact missing-header compiler error.
        # Otherwise fail immediately and preserve the original diagnostics.
        attempted: set[str] = set()
        while True:
            proc = subprocess.run(
                argv, cwd=str(cwd), stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT, text=True, timeout=900, check=False
            )
            if proc.returncode == 0:
                print(f"GAZELLE_ANDROID_ARMV7_TU_PASS path={suffix}", flush=True)
                break
            if proc.stdout:
                print(proc.stdout[-28000:], flush=True)
            prereq = recoverable_prerequisite(proc.stdout or "", attempted)
            if not prereq or len(attempted) >= MAX_DEPENDENCY_RECOVERIES:
                raise RuntimeError(
                    f"GAZELLE_ANDROID_ARMV7_TU_FAIL {suffix} exit={proc.returncode} "
                    f"prerequisites_attempted={sorted(attempted)}"
                )
            attempted.add(prereq)
            print(f"GAZELLE_ANDROID_KNOWN_HEADER_RECOVERY_START target={prereq}", flush=True)
            build = subprocess.run(
                ["cmake", "--build", str(database.resolve().parent), "--target", prereq,
                 "--parallel", "2"],
                cwd=str(cwd), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                text=True, timeout=3600, check=False
            )
            if build.returncode:
                if build.stdout:
                    print(build.stdout[-18000:], flush=True)
                raise RuntimeError(
                    f"GAZELLE_ANDROID_KNOWN_HEADER_RECOVERY_FAIL target={prereq} "
                    f"exit={build.returncode}"
                )
            print(f"GAZELLE_ANDROID_KNOWN_HEADER_RECOVERY_PASS target={prereq}", flush=True)

    print(
        "GAZELLE_ANDROID_ARMV7_TWO_TU_COMPILE_PASS "
        "video_worker=true bitstream_converter=true "
        "apk=false runtime=false authentic_fel=false no_device=true",
        flush=True,
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("compile_commands", type=Path)
    ap.add_argument("source_root", type=Path)
    args = ap.parse_args()
    compile_units(args.compile_commands, args.source_root)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(f"GAZELLE_ANDROID_TU_COMPILE_REFUSED {exc}", file=sys.stderr, flush=True)
        sys.exit(1)
